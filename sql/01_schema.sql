CREATE TABLE inv_categories (
  category_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR2(80) NOT NULL,
  CONSTRAINT inv_categories_name_uk UNIQUE (category_name)
);

CREATE TABLE inv_suppliers (
  supplier_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_name VARCHAR2(120) NOT NULL,
  phone         VARCHAR2(30),
  email         VARCHAR2(150),
  CONSTRAINT inv_suppliers_name_uk UNIQUE (supplier_name)
);

CREATE TABLE inv_products (
  product_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku           VARCHAR2(30)  NOT NULL,
  product_name  VARCHAR2(150) NOT NULL,
  category_id   NUMBER        NOT NULL REFERENCES inv_categories (category_id),
  supplier_id   NUMBER        REFERENCES inv_suppliers (supplier_id),
  unit_price    NUMBER(12,2)  NOT NULL,
  qty_on_hand   NUMBER        DEFAULT 0 NOT NULL,
  reorder_level NUMBER        DEFAULT 10 NOT NULL,
  is_active     VARCHAR2(1)   DEFAULT 'Y' NOT NULL,
  CONSTRAINT inv_products_sku_uk    UNIQUE (sku),
  CONSTRAINT inv_products_price_ck  CHECK (unit_price >= 0),
  CONSTRAINT inv_products_qty_ck    CHECK (qty_on_hand >= 0),
  CONSTRAINT inv_products_active_ck CHECK (is_active IN ('Y', 'N'))
);

CREATE TABLE inv_stock_movements (
  movement_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id    NUMBER       NOT NULL REFERENCES inv_products (product_id),
  movement_type VARCHAR2(3)  NOT NULL,
  quantity      NUMBER       NOT NULL,
  movement_date DATE         DEFAULT SYSDATE NOT NULL,
  reference     VARCHAR2(200),
  created_by    VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER),
  CONSTRAINT inv_movements_type_ck CHECK (movement_type IN ('IN', 'OUT')),
  CONSTRAINT inv_movements_qty_ck  CHECK (quantity > 0)
);

CREATE INDEX inv_movements_product_ix ON inv_stock_movements (product_id, movement_date);

-- Every movement updates QTY_ON_HAND; stock can never go below zero
CREATE OR REPLACE TRIGGER inv_stock_movements_bi
  BEFORE INSERT ON inv_stock_movements
  FOR EACH ROW
DECLARE
  l_qty inv_products.qty_on_hand%TYPE;
BEGIN
  SELECT qty_on_hand INTO l_qty
    FROM inv_products
   WHERE product_id = :NEW.product_id
     FOR UPDATE;

  IF :NEW.movement_type = 'OUT' AND :NEW.quantity > l_qty THEN
    RAISE_APPLICATION_ERROR(-20201,
      'Not enough stock: ' || l_qty || ' on hand, ' || :NEW.quantity || ' requested.');
  END IF;

  UPDATE inv_products
     SET qty_on_hand = qty_on_hand + CASE :NEW.movement_type WHEN 'IN' THEN :NEW.quantity ELSE -:NEW.quantity END
   WHERE product_id = :NEW.product_id;
END;
/

-- Products at or below their reorder level
CREATE OR REPLACE VIEW inv_low_stock_v AS
SELECT p.product_id,
       p.sku,
       p.product_name,
       c.category_name,
       s.supplier_name,
       p.qty_on_hand,
       p.reorder_level,
       GREATEST(p.reorder_level * 2 - p.qty_on_hand, 0) AS suggested_order_qty,
       CASE WHEN p.qty_on_hand = 0 THEN 'Out of stock' ELSE 'Low stock' END AS stock_status
  FROM inv_products p
  JOIN inv_categories c ON c.category_id = p.category_id
  LEFT JOIN inv_suppliers s ON s.supplier_id = p.supplier_id
 WHERE p.is_active = 'Y'
   AND p.qty_on_hand <= p.reorder_level;

